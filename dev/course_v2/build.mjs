// Builds public/assets/course.js and supabase/28b_course_v2.sql from dev/course_v2/content.mjs.
// Run: node dev/course_v2/build.mjs
import fs from "fs";
import { TRACKS, STAGES, buildWeeks } from "./content.mjs";

const root = new URL("../../", import.meta.url);
const STAFF = ["Supervisor grading", "Supervisor performance evaluation"];
const out = { stages: STAGES, tracks: {} }, rows = [], titles = [];
const q = (s) => "$q$" + String(s) + "$q$";

for (const t of Object.keys(TRACKS)) {
  out.tracks[t] = buildWeeks(t).map((w, wi) => {
    titles.push(`(${q(t)}, ${wi + 1}, ${q(w.title)})`);
    return {
      week: wi + 1, stage: w.stage, title: w.title, objectives: w.objectives || null, resources: w.resources || null,
      items: w.items.map((it, ii) => {
        const key = `w${wi + 1}-${ii + 1}`, o = { key, type: it.type, title: it.title };
        for (const k of ["mins", "points", "intro", "detail", "link", "opt", "proj", "wk", "paper", "final"]) if (it[k] != null && it[k] !== false) o[k] = it[k];
        rows.push(`(${q(t)}, ${wi + 1}, ${q(key)}, ${q(it.type)}, ${q(it.title)}, ${!!it.proj}, ${!!it.opt}, ${!!it.link}, ${STAFF.includes(it.title)}, ${it.paper ? q(it.paper) : "null"}, ${!!it.final})`);
        return o;
      }),
    };
  });
}

fs.writeFileSync(new URL("public/assets/course.js", root),
  "// The programme, week by week, for each track. Generated by dev/course_v2/build.mjs. Assessment answers are kept on the server.\nexport const COURSE = " + JSON.stringify(out) + ";\n");

const sql = `-- Jobnest Academy update 28b: the 20-week programme for the three tracks (generated by dev/course_v2/build.mjs).
delete from course_items;
insert into course_items(track_code, week, key, type, title, proj, opt, link, staff, paper, final) values
${rows.join(",\n")};
delete from course_weeks;
insert into course_weeks(track_code, week, title) values
${titles.join(",\n")};
select 'Programme v2 course installed' as done, (select count(*) from course_items) as course_items;
`;
fs.writeFileSync(new URL("supabase/28b_course_v2.sql", root), sql);
console.log("tracks", Object.keys(out.tracks), "items", rows.length, "weeks", titles.length);
